import type {
  Equipment,
  Exercise,
  ExerciseCategory,
  MovementPattern,
  MuscleGroup,
  MuscleSlug,
  TrainingLocation,
} from '@/types';

/**
 * Встроенная библиотека упражнений FORM.
 * media — папка в открытой базе free-exercise-db (Unlicense / public domain):
 * две фотографии фаз движения, которые карточка упражнения показывает плавной
 * циклической анимацией.
 */

const SLUG_GROUP: Record<MuscleSlug, MuscleGroup | null> = {
  chest: 'chest',
  deltoids: 'shoulders',
  biceps: 'biceps',
  triceps: 'triceps',
  forearm: 'forearms',
  abs: 'abs',
  obliques: 'abs',
  quadriceps: 'quads',
  adductors: 'quads',
  tibialis: 'calves',
  calves: 'calves',
  trapezius: 'back',
  'upper-back': 'back',
  'lower-back': 'back',
  gluteal: 'glutes',
  hamstring: 'hamstrings',
  neck: null,
};

const LOADED: Equipment[] = ['barbell', 'dumbbell', 'kettlebell', 'machine', 'cable', 'ezbar', 'smith'];
const HOME_EQUIPMENT: Equipment[] = ['bodyweight', 'dumbbell', 'kettlebell', 'band', 'bench', 'pullupbar'];

function groupsOf(slugs: MuscleSlug[]): MuscleGroup[] {
  const out: MuscleGroup[] = [];
  for (const s of slugs) {
    const g = SLUG_GROUP[s];
    if (g && !out.includes(g)) out.push(g);
  }
  return out;
}

type Def = [
  id: string,
  name: string,
  nameEn: string,
  category: ExerciseCategory,
  pattern: MovementPattern,
  mechanic: 'c' | 'i',
  equipment: Equipment[],
  primary: MuscleSlug[],
  secondary: MuscleSlug[],
  reps: [number, number],
  increment: number,
  tier: 1 | 2 | 3,
  media: string | undefined,
  cues: string[],
  mistakes: string[],
];

function build(d: Def): Exercise {
  const [id, name, nameEn, category, pattern, mech, equipment, primary, secondary, reps, increment, tier, media, cues, mistakes] = d;
  const primaryGroups = groupsOf(primary);
  const secondaryGroups = groupsOf(secondary).filter((g) => !primaryGroups.includes(g));
  const location: TrainingLocation[] = equipment.every((e) => HOME_EQUIPMENT.includes(e)) ? ['gym', 'home'] : ['gym'];
  return {
    id,
    name,
    nameEn,
    category,
    pattern,
    primary,
    secondary,
    groups: { primary: primaryGroups, secondary: secondaryGroups },
    equipment,
    mechanic: mech === 'c' ? 'compound' : 'isolation',
    location,
    bodyweight: !equipment.some((e) => LOADED.includes(e)),
    increment,
    defaultReps: reps,
    tier,
    cues,
    mistakes,
    media,
  };
}

