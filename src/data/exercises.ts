/** Сколько секунд в среднем занимает один рабочий подход (без отдыха) */
export function secondsPerSet(ex: Exercise): number {
  return ex.pattern === 'core' || ex.pattern === 'carry' ? 45 : ex.mechanic === 'compound' ? 50 : 40;
}
