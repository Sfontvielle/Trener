/** Слово → варианты для поиска: синонимы своей группы и виды категории (без самого слова) */
export const SYNONYM_INDEX: Map<string, string[]> = (() => {
  const m = new Map<string, Set<string>>();
  const add = (w: string, list: string[]) => {
    const s = m.get(w) ?? new Set<string>();
    for (const x of list) if (x !== w) s.add(x);
    m.set(w, s);
  };
  for (const g of FOOD_SYNONYMS) for (const w of g) add(w, g);
  for (const [cat, kinds] of Object.entries(FOOD_CATEGORIES)) add(cat, kinds);
  return new Map([...m.entries()].map(([k, v]) => [k, [...v]]));
})();
