export function techniqueFor(ex: Exercise): Technique {
  const base = P[ex.pattern];
  const setup = [...base.setup];
  const safety = [...base.safety];
  if (ex.equipment.includes('machine') || ex.equipment.includes('smith')) setup.unshift('Настрой тренажёр под рост: ось вращения совпадает с работающим суставом');
  if (ex.equipment.includes('cable')) setup.push('Трос натянут уже в начальной точке — без провиса');
  if (ex.bodyweight && ex.mechanic === 'compound') safety.push('Когда легко делаешь верх диапазона — добавь отягощение или замедли опускание');
  const used = new Set<MuscleSlug>([...ex.primary, ...ex.secondary]);
  return { setup, range: base.range, breathing: base.breathing, safety, stabilizers: base.stab.filter((m) => !used.has(m)) };
}
