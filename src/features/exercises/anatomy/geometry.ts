/** Ширина туловища по высоте (доля мужской): плечи и талия уже, таз шире */
const TORSO_F: [number, number][] = [[40, 0.93], [62, 0.92], [72, 0.89], [100, 0.9], [125, 0.86], [140, 0.85], [155, 0.9], [170, 0.99], [190, 1.07], [212, 1.07]];
const LEG_F: [number, number][] = [[190, 1.07], [215, 1.07], [245, 1.05], [290, 1.0], [330, 0.97], [400, 0.95]];
const ARM_SHIFT = 46 * (1 - 0.89);

function interp(tab: [number, number][], y: number): number {
  if (y <= tab[0][0]) return tab[0][1];
  for (let i = 1; i < tab.length; i++) {
    if (y <= tab[i][0]) {
      const [y0, v0] = tab[i - 1];
      const [y1, v1] = tab[i];
      return v0 + ((v1 - v0) * (y - y0)) / (y1 - y0);
    }
  }
  return tab[tab.length - 1][1];
}

function femaleWarp(p: Pt, r: Region): Pt {
  const [x, y] = p;
  let nx = x;
  let ny = y;
  if (r === 'h') {
    nx = x * 0.93;
    ny = 3 + y * 0.94;
  } else if (r === 't') nx = x * interp(TORSO_F, y);
  else if (r === 'l') nx = x * interp(LEG_F, y);
  else {
    // рука: сдвиг вместе с плечом и тоньше вокруг своей оси
    const axis = -51 - ((y - 85) * 16) / 120;
    nx = x + ARM_SHIFT - (x - axis) * 0.1;
  }
  return p.length === 3 ? [nx, ny, 1] : [nx, ny];
}

