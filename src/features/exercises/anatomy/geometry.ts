// ---------- построение путей ----------

const f1 = (n: number) => (Math.round(n * 10) / 10).toString();

function smooth(pts: Pt[], closed: boolean): string {
  const n = pts.length;
  const at = (i: number) => (closed ? pts[(i + n) % n] : pts[Math.max(0, Math.min(n - 1, i))]);
  let d = `M${f1(pts[0][0])} ${f1(pts[0][1])}`;
  const segs = closed ? n : n - 1;
  for (let i = 0; i < segs; i++) {
    const p0 = at(i - 1);
    const p1 = at(i);
    const p2 = at(i + 1);
    const p3 = at(i + 2);
    const c1 = p1.length === 3 ? p1 : [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = p2.length === 3 ? p2 : [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${f1(c1[0])} ${f1(c1[1])} ${f1(c2[0])} ${f1(c2[1])} ${f1(p2[0])} ${f1(p2[1])}`;
  }
  return closed ? `${d}Z` : d;
}

function along(poly: Pt[], u: number): [number, number] {
  if (poly.length === 1) return [poly[0][0], poly[0][1]];
  const seg: number[] = [];
  let total = 0;
  for (let i = 1; i < poly.length; i++) {
    const l = Math.hypot(poly[i][0] - poly[i - 1][0], poly[i][1] - poly[i - 1][1]);
    seg.push(l);
    total += l;
  }
  let t = u * total;
  for (let i = 0; i < seg.length; i++) {
    if (t <= seg[i] || i === seg.length - 1) {
      const k = seg[i] ? Math.min(1, t / seg[i]) : 0;
      return [poly[i][0] + (poly[i + 1][0] - poly[i][0]) * k, poly[i][1] + (poly[i + 1][1] - poly[i][1]) * k];
    }
    t -= seg[i];
  }
  return [poly[0][0], poly[0][1]];
}

/** Волокна: от линии начала к прикреплению, слегка выгнуты к «брюшку» мышцы */
function fibers(def: Def, pts: Pt[], fib: { a: Pt[]; b: Pt[]; n: number }): string {
  const cx = pts.reduce((s, p) => s + p[0], 0) / pts.length;
  const cy = pts.reduce((s, p) => s + p[1], 0) / pts.length;
  let d = '';
  for (let k = 1; k <= fib.n; k++) {
    const u = k / (fib.n + 1);
    const a = along(fib.a, u);
    const b = along(fib.b, u);
    const a2 = [a[0] + (b[0] - a[0]) * 0.06, a[1] + (b[1] - a[1]) * 0.06];
    const b2 = [b[0] - (b[0] - a[0]) * 0.06, b[1] - (b[1] - a[1]) * 0.06];
    const mx = (a2[0] + b2[0]) / 2;
    const my = (a2[1] + b2[1]) / 2;
    const c = [mx + (cx - mx) * 0.22, my + (cy - my) * 0.22];
    d += `M${f1(a2[0])} ${f1(a2[1])}Q${f1(c[0])} ${f1(c[1])} ${f1(b2[0])} ${f1(b2[1])}`;
  }
  return d;
}

function build(defs: Def[], sex: Sex): Shape[] {
  const out: Shape[] = [];
  const tf = (p: Pt, r: Region): Pt => (sex === 'female' ? femaleWarp(p, r) : p);
  for (const def of defs) {
    const sides = def.mid ? [1] : [1, -1];
    for (const s of sides) {
      const map = (p: Pt): Pt => {
        const q = tf(p, def.r);
        return q.length === 3 ? [q[0] * s, q[1], 1] : [q[0] * s, q[1]];
      };
      const pts = def.pts.map(map);
      const xs = pts.map((p) => p[0]);
      const ys = pts.map((p) => p[1]);
      const box: Shape['box'] = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
      const shape: Shape = { id: `${def.id}${def.mid ? '' : s > 0 ? '-l' : '-r'}`, base: def.id, slug: def.slug, box, kind: def.kind ?? 'muscle', d: smooth(pts, !def.open) };
      if (def.fib) shape.fib = fibers(def, pts, { a: def.fib.a.map(map), b: def.fib.b.map(map), n: def.fib.n });
      out.push(shape);
    }
  }
  return out;
}

/** Женские дополнения уже в женских координатах (без пересчёта пропорций) */
function buildExtra(defs: Def[]): Shape[] {
  return build(defs, 'male');
}

const cache = new Map<string, Shape[]>();

/** Контуры фигуры по порядку рисования: кожа → мышцы и сухожилия → (у женской) грудь и причёска */
export function figure(sex: Sex, view: View): Shape[] {
  const key = `${sex}-${view}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const female = sex === 'female';
  const shapes = [
    ...build(view === 'front' ? SKIN_F : SKIN_B, sex),
    ...build(view === 'front' ? FRONT : BACK, sex),
    ...(female ? buildExtra(view === 'front' ? FEMALE_FRONT : FEMALE_BACK) : []),
  ];
  cache.set(key, shapes);
  return shapes;
}

/** Какие группы мышц видны с этой стороны (для подписи «есть нагруженные мышцы») */
export function slugsOn(view: View): Set<MuscleSlug> {
  return new Set((view === 'front' ? FRONT : BACK).map((d) => d.slug).filter((s): s is MuscleSlug => !!s));
}

