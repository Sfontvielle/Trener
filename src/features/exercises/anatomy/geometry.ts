/**
 * Анатомическая фигура RYNJI (своя, без сторонних рисунков): спереди и сзади, мужская и женская.
 *
 * Каждая мышца — отдельный контур (головки — отдельно), внутри — волокна от начала к прикреплению,
 * сухожилия и апоневрозы — светлыми (ключица, белая линия и сухожильные перемычки пресса, надколенник,
 * ахиллово сухожилие, поясничная фасция, подвздошно-большеберцовый тракт, ость лопатки).
 *
 * Координаты: центр тела x = 0, макушка y = 0, стопы y = 400 (рост ≈ 8 голов). Описана левая половина
 * (x < 0), правая получается зеркалом. Женская фигура — те же мышцы с другими пропорциями (уже плечи
 * и талия, шире таз, руки тоньше) плюс грудь и причёска.
 */
import type { MuscleSlug, Sex } from '@/types';

/** Точка контура; третий элемент 1 — угол (без сглаживания: сухожильный «хвост» мышцы) */
type Pt = [number, number] | [number, number, 1];
type Region = 'h' | 't' | 'a' | 'l';
export type ShapeKind = 'skin' | 'neutral' | 'muscle' | 'tendon' | 'line' | 'hair' | 'contour';
export type View = 'front' | 'back';

interface Def {
  id: string;
  /** Группа мышц приложения, к которой относится контур (по ней — подсветка) */
  slug?: MuscleSlug;
  kind?: ShapeKind;
  r: Region;
  pts: Pt[];
  /** Волокна: от линии начала a к линии прикрепления b, n штук */
  fib?: { a: Pt[]; b: Pt[]; n: number };
  /** Открытая линия (сухожильная перемычка, паховая связка) */
  open?: boolean;
  /** Контур симметричен сам по себе (на оси тела) — не зеркалить */
  mid?: boolean;
}

export interface Shape {
  id: string;
  /** id контура без стороны (-l / -r) — по нему уточнение по головкам */
  base: string;
  slug?: MuscleSlug;
  /** Рамка контура: x0, y0, x1, y1 */
  box: [number, number, number, number];
  kind: ShapeKind;
  d: string;
  /** Волокна одной строкой путей */
  fib?: string;
}

